"""Regenerate flowwriter/lucide_icons.py from the Lucide icon set (ISC licence).

Run on a development machine with internet access; the app itself never downloads icons:

    python scripts/fetch_icons.py

Icons are fetched from the Iconify API (https://api.iconify.design/lucide/<name>.svg),
reduced to their shape elements, and written as a plain Python dictionary so the packaged
app needs no extra data files. Edit ICONS below to add or change an icon.
"""
from __future__ import annotations

from pathlib import Path
from urllib.request import Request, urlopen
import xml.etree.ElementTree as ET

# app icon name -> Lucide icon name
ICONS = {
    # navigation and general
    "overview": "layout-grid", "history": "history", "insights": "chart-column", "edit": "pencil",
    "actions": "zap", "providers": "server", "shield": "shield-check", "keyboard": "keyboard",
    "lock": "lock", "search": "search", "star": "star", "plus": "plus", "check": "check",
    "close": "x", "copy": "copy", "trash": "trash-2", "reuse": "rotate-ccw", "sparkles": "sparkles",
    "arrow": "arrow-right", "arrow-up": "arrow-up-right",
    "chevron": "chevron-right", "chevron-left": "chevron-left", "chevron-down": "chevron-down",
    # one icon per built-in action, looked up by action name (see icons.ACTION_ICONS)
    "summarize": "align-left", "rephrase": "repeat-2", "refine": "wand-sparkles", "improve": "trending-up",
    "professional": "briefcase", "concise": "minimize-2", "grammar": "spell-check", "bullets": "list",
    "friendly": "smile", "expand": "maximize-2", "executive": "file-text", "code": "code",
    "prompt": "message-square-text", "translate": "languages", "custom": "pencil-line",
}
SHAPES = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}
STYLE = {"fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "color"}   # the app sets these
OUT = Path(__file__).resolve().parents[1] / "flowwriter" / "lucide_icons.py"


def shapes_of(svg_text: str) -> str:
    """Only the drawing elements, without the wrapper's stroke, fill or size attributes."""
    root = ET.fromstring(svg_text)
    out = []
    for element in root.iter():
        tag = element.tag.split("}")[-1]
        if tag in SHAPES:
            attributes = " ".join(f'{key}="{value}"' for key, value in element.attrib.items() if key not in STYLE)
            out.append(f"<{tag} {attributes}/>")
    if not out:
        raise ValueError("no drawable shapes found")
    return "".join(out)


def main() -> None:
    lines = [
        '"""Lucide icons (https://lucide.dev), ISC licence. GENERATED by scripts/fetch_icons.py: do not edit.',
        "",
        "Copyright (c) Lucide Icons and Contributors. See THIRD_PARTY_NOTICES.md for the licence text.",
        '"""',
        "",
        "LUCIDE = {",
    ]
    for name, lucide in ICONS.items():
        request = Request(f"https://api.iconify.design/lucide/{lucide}.svg", headers={"User-Agent": "icon-fetch-script"})
        with urlopen(request, timeout=20) as response:
            lines.append(f'    "{name}": {shapes_of(response.read().decode("utf-8"))!r},  # lucide:{lucide}')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(ICONS)} icons to {OUT}")


if __name__ == "__main__":
    main()
